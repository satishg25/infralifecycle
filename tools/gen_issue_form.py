#!/usr/bin/env python3
"""Generate the GitHub Issue Form from a customer profile.

Dropdown options come from the profile's catalogue and policy, so the form can only offer
values the pipeline will accept. Switching customer = regenerate the form from their profile.

Usage: gen_issue_form.py <profile_dir> [--out PATH] [--check]
  --check  exit 1 if PATH is not up to date (used in CI)
"""
import argparse
import re
import sys
from pathlib import Path

import yaml

sys.path.insert(0, str(Path(__file__).parent))
from form_fields import CONFIRM_TEXT, FIELDS, FORM_TO_REQUEST_VALUE, TITLE_PREFIX  # noqa: E402

HELP = {
    "name": "Lower-case letters, digits and hyphens; 3-24 characters (e.g. sample-app01).",
    "data_disk_gb": "Leave empty for the profile default.",
    "owner": "Used for tagging. Leave empty if unsure.",
    "ttl_days": "Auto-cleanup hint for lab environments (1-90).",
}


def options_for(field: str, profile: dict, catalogue: dict) -> list[str]:
    if field == "environment":
        return list(profile["policy"]["allowed_environments"])
    if field == "sizing":
        return list(catalogue["sizing"])
    if field == "image":
        return list(catalogue["images"])
    if field == "network_profile":
        return list(catalogue["networks"])
    if field == "middleware":
        return ["no-middleware", "jboss"]
    raise KeyError(field)


def build(profile_dir: Path) -> str:
    profile = yaml.safe_load((profile_dir / "profile.yml").read_text())["profile"]
    catalogue = yaml.safe_load((profile_dir / "catalogue.yml").read_text())["catalogue"]
    body = []
    for field, label, kind, required in FIELDS:
        if kind == "checkbox":
            body.append({"type": "checkboxes", "id": field.lstrip("_"),
                         "attributes": {"label": label, "options": [{"label": CONFIRM_TEXT, "required": True}]}})
            continue
        attrs = {"label": label}
        if field in HELP:
            attrs["description"] = HELP[field]
        item = {"type": kind, "id": field, "attributes": attrs, "validations": {"required": required}}
        if kind == "dropdown":
            attrs["options"] = options_for(field, profile, catalogue)
        body.append(item)
    form = {
        "name": "Platform request",
        "description": f"Request a machine (profile: {profile['name']}). Triggers a read-only plan.",
        "title": TITLE_PREFIX,
        "labels": ["platform-request"],
        "body": body,
    }
    _self_check(form)
    header = "# GENERATED by tools/gen_issue_form.py from the customer profile - do not edit by hand.\n"
    return header + yaml.safe_dump(form, sort_keys=False, width=100)


def _self_check(form: dict) -> None:
    """Fail the generator on things GitHub rejects, so a bad form never reaches the repo."""
    for item in form["body"]:
        assert re.fullmatch(r"[A-Za-z0-9_-]+", item["id"]) and not item["id"].startswith("_"), item["id"]
        for opt in item["attributes"].get("options", []):
            text = opt["label"] if isinstance(opt, dict) else opt
            assert text.strip().lower() != "none", f"GitHub reserves dropdown option 'None' ({item['id']})"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("profile_dir", type=Path)
    ap.add_argument("--out", type=Path, default=Path(".github/ISSUE_TEMPLATE/platform-request.yml"))
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    text = build(args.profile_dir)
    if args.check:
        if not args.out.exists() or args.out.read_text() != text:
            print(f"STALE {args.out}: regenerate with tools/gen_issue_form.py {args.profile_dir}")
            return 1
        print(f"OK {args.out} is up to date")
        return 0
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(text)
    print(f"wrote {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
